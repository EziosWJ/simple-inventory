// Inventory adjustment presentation and confirmation, with all API traffic mocked.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { setTimeout as delay } from 'node:timers/promises';
import { chromium } from 'playwright';

const base = 'http://127.0.0.1:4214';
const vite = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '4214', '--strictPort'], { cwd: new URL('..', import.meta.url), stdio: 'ignore' });
const line = { id: 1, productId: 1, productCode: 'AD-G', productName: '历史商品快照', productModel: '原型号', unit: '台', quantity: '2', reason: 'OPENING', remark: '调整行备注' };
const draft = { id: 1, documentNo: 'AD-001', status: 'DRAFT', version: 1, createdBy: 1, createdByName: '创建人', createTime: '2026-10-13T00:00:00Z', postedBy: null, postedAt: null, cancelledBy: null, cancelledAt: null, items: [line, { ...line, id: 2, productId: 2, productName: '第二商品', quantity: '-1', reason: 'DAMAGE', unit: '支' }] };
let document = structuredClone(draft), postStatus = 400, losePostResponse = false;
const writes = [], errors = [];
let browser;
try {
  for (let i = 0; i < 80; i++) { try { if ((await fetch(base)).ok) break; } catch { /* starting */ } await delay(100); }
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => localStorage.setItem('web-auth', JSON.stringify({ token: 'adjustment-dialog-fixture', user: null })));
  await context.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname;
    if (!path.startsWith('/api/')) return route.continue();
    if (route.request().method() !== 'GET') {
      writes.push({ path, body: route.request().postDataJSON() });
      if (losePostResponse) return route.abort('failed');
      return route.fulfill({ status: postStatus, contentType: 'application/json', body: JSON.stringify({ code: postStatus, message: postStatus === 409 ? '版本已变化' : '库存不足，整单拒绝', data: null }) });
    }
    let data = { records: [], total: 0, page: 1, pageSize: 10 };
    if (path === '/api/auth/me') data = { id: 1, username: 'fixture', roles: [] };
    else if (path === '/api/auth/menus') data = [];
    else if (path.includes('/dict/')) data = [];
    else if (path.endsWith('/unread-count')) data = 0;
    else if (path === '/api/v1/inventory/adjustments') data = { records: [document], total: 1, page: 1, pageSize: 10 };
    else if (path === '/api/v1/inventory/adjustments/1') data = document;
    else if (path === '/api/v1/inventory/entries') data = { records: [{ ...line, id: 90, adjustmentId: 1, sourceType: 'ADJUSTMENT', entryType: 'ORIGINAL', documentNo: document.documentNo, occurredAt: draft.createTime, balanceBefore: '5', balanceAfter: '7', operatorName: '过账人' }], total: 1, page: 1, pageSize: 10 };
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ code: 200, message: 'OK', data }) });
  });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/business/inventory-adjustments`);
  await page.getByRole('button', { name: '查看', exact: true }).click();
  let detail = page.getByRole('dialog');
  await detail.getByText('增加 2 台', { exact: true }).waitFor();
  await detail.getByText('减少 1 支', { exact: true }).waitFor();
  assert.equal(await detail.getByText('调整前 → 调整后', { exact: true }).count(), 0, 'draft has no invented stock balances');
  await detail.getByRole('button', { name: '关闭', exact: true }).click();
  await detail.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '过账', exact: true }).click();
  const confirmation = page.getByRole('dialog', { name: '过账库存调整单', exact: true });
  await confirmation.waitFor();
  const submit = confirmation.getByRole('button', { name: '确认并过账', exact: true });
  assert.ok(await submit.isDisabled(), 'whole-document acknowledgement remains required');
  await confirmation.getByRole('button', { name: '返回核对', exact: true }).click();
  assert.equal(writes.length, 0);
  await page.getByRole('dialog').getByRole('button', { name: '过账', exact: true }).click();
  await confirmation.getByRole('checkbox').check();
  await submit.click();
  await confirmation.getByRole('alert').filter({ hasText: '库存不足' }).waitFor();
  assert.deepEqual(writes[0].body, { version: 1 });
  assert.ok(await confirmation.isVisible(), 'rejection keeps the confirmation and document');
  postStatus = 409;
  await submit.click();
  await confirmation.getByRole('alert').filter({ hasText: '单据状态或版本已变化' }).waitFor();
  assert.ok(await submit.isDisabled(), 'conflict stops old confirmation');
  await confirmation.getByRole('button', { name: '返回核对', exact: true }).click();
  losePostResponse = true;
  await page.getByRole('dialog').getByRole('button', { name: '过账', exact: true }).click();
  await confirmation.getByRole('checkbox').check();
  await submit.click();
  await confirmation.getByRole('alert').filter({ hasText: '过账结果尚待核实' }).waitFor();
  assert.ok(await submit.isDisabled(), 'unknown outcome cannot replay the old confirmation');
  await confirmation.getByRole('button', { name: '重新加载最新单据', exact: true }).waitFor();
  await confirmation.getByRole('button', { name: '返回核对', exact: true }).click();
  losePostResponse = false;
  document = { ...draft, status: 'CANCELLED', postedBy: 1, postedByName: '过账人', postedAt: '2026-10-13T01:00:00Z', cancelledByName: '取消人', cancelledAt: '2026-10-13T02:00:00Z', cancelReason: '录错调整', items: [{ ...line, balanceBefore: '5', balanceAfter: '7' }] };
  await page.goto(`${base}/business/inventory-entries`);
  await page.getByRole('button', { name: 'AD-001', exact: true }).click();
  detail = page.getByRole('dialog');
  await detail.getByText('5 → 7 台', { exact: true }).waitFor();
  await detail.getByText('取消原因：录错调整', { exact: true }).waitFor();
  assert.equal(await detail.getByRole('button', { name: '过账', exact: true }).count(), 0, 'source view does not gain maintenance actions');
  await detail.screenshot({ path: '/tmp/issue90-adjustment-detail.png' });
  await detail.getByRole('button', { name: '关闭', exact: true }).click();
  document = { ...draft, items: Array.from({ length: 24 }, (_, i) => ({ ...line, id: i + 1, productId: i + 1 })) };
  await page.setViewportSize({ width: 1024, height: 600 });
  await page.goto(`${base}/business/inventory-adjustments`);
  await page.getByRole('button', { name: '过账', exact: true }).click();
  await confirmation.waitFor();
  const footer = await confirmation.locator('footer').boundingBox();
  assert.ok(footer.y >= 0 && footer.y + footer.height <= 600);
  await confirmation.locator('div.overflow-y-auto').evaluate(node => { node.scrollTop = node.scrollHeight; });
  assert.equal((await confirmation.locator('footer').boundingBox()).y, footer.y, 'long confirmation actions stay fixed');
  await confirmation.screenshot({ path: '/tmp/issue90-adjustment-confirm.png' });
  await confirmation.getByRole('button', { name: '返回核对', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 800 });
  await page.getByRole('button', { name: '查看', exact: true }).click();
  const rect = await page.getByRole('dialog').boundingBox();
  assert.equal(Math.round(rect.width), 390);
  assert.ok(rect.y >= 0 && rect.y + rect.height <= 800);
  assert.deepEqual(errors, []);
  console.log('PASS adjustment modals: shared detail/source, real snapshot balances, increase/decrease units, acknowledgement, no-write cancel, rejection/conflict, short-screen fixed actions and narrow layout');
} finally { await browser?.close(); vite.kill('SIGTERM'); }
